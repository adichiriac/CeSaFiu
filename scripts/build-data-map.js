#!/usr/bin/env node
/**
 * Rebuild the standalone, self-contained data-map HTML by inlining the
 * canonical /data JSON source into cesafiu-data-map.html.
 *
 * Usage: node scripts/build-data-map.js
 *
 * Output: cesafiu-data-map-standalone.html (sibling of cesafiu-data-map.html)
 *
 * Run this whenever data.js or the map template is updated.
 */
const fs = require('fs');
const path = require('path');

const {loadCandidateData, loadCanonicalData} = require('./data-source');

const repoRoot = path.resolve(__dirname, '..');
const TEMPLATE = path.join(repoRoot, 'cesafiu-data-map.html');
const OUT = path.join(repoRoot, 'cesafiu-data-map-standalone.html');

if (!fs.existsSync(TEMPLATE)) { console.error('Missing:', TEMPLATE); process.exit(1); }

const html = fs.readFileSync(TEMPLATE, 'utf8');
const dataJs = `window.QUIZ_DATA = ${JSON.stringify(loadCanonicalData(), null, 2)};`;
const candidateJs = `window.QUIZ_DATA = window.QUIZ_DATA || {};\nwindow.QUIZ_DATA.careerCandidates = ${JSON.stringify(loadCandidateData(), null, 2)};`;

const tag = '<script src="cesafiu_prototype_v3/project/data.js"></script>';
const candidateTag = '<script src="cesafiu_prototype_v3/project/career-candidates.js"></script>';
const inline = `<script>\n/* === Inlined from /data JSON (auto-generated by scripts/build-data-map.js — do not edit) === */\n${dataJs}\n</script>`;
const candidateInline = `<script>\n/* === Inlined from data/career-candidates.json (auto-generated by scripts/build-data-map.js — do not edit) === */\n${candidateJs}\n</script>`;

if (!html.includes(tag) || !html.includes(candidateTag)) {
  console.error('Could not find script tag to replace. Template may have been edited.');
  process.exit(1);
}

const out = html
  .replace(tag, inline)
  .replace(candidateTag, candidateInline)
  .replace(
    'data: /data JSON · artifact cesafiu_prototype_v3/project/data.js',
    `data: inlined /data JSON + candidates · built ${new Date().toISOString().slice(0, 10)}`
  );

fs.writeFileSync(OUT, out, 'utf8');
const sizeKB = (fs.statSync(OUT).size / 1024).toFixed(1);
console.log(`Built ${path.relative(repoRoot, OUT)} (${sizeKB} KB)`);
