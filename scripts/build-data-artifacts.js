#!/usr/bin/env node
/**
 * Build legacy data artifacts from the canonical /data JSON source.
 *
 * Source of truth:
 *   data/*.json
 *
 * Generated compatibility artifact:
 *   cesafiu_prototype_v3/project/data.js
 */
const fs = require('fs');
const path = require('path');

const {loadCandidateData, loadCanonicalData, repoRoot} = require('./data-source');

const OUT = path.join(repoRoot, 'cesafiu_prototype_v3/project/data.js');
const CANDIDATES_OUT = path.join(repoRoot, 'cesafiu_prototype_v3/project/career-candidates.js');

const data = loadCanonicalData();
const body = JSON.stringify(data, null, 2);
const content = [
  '// CeSaFiu data artifact. Auto-generated by scripts/build-data-artifacts.js.',
  '// Do not edit manually; update data/*.json instead.',
  `window.QUIZ_DATA = ${body};`,
  '',
].join('\n');

fs.writeFileSync(OUT, content, 'utf8');
const sizeKB = (fs.statSync(OUT).size / 1024).toFixed(1);
console.log(`Built ${path.relative(repoRoot, OUT)} (${sizeKB} KB)`);

const candidatesBody = JSON.stringify(loadCandidateData(), null, 2);
const candidatesContent = [
  '// CeSaFiu career candidate artifact. Auto-generated by scripts/build-data-artifacts.js.',
  '// Do not edit manually; update data/career-candidates.json instead.',
  'window.QUIZ_DATA = window.QUIZ_DATA || {};',
  `window.QUIZ_DATA.careerCandidates = ${candidatesBody};`,
  '',
].join('\n');

fs.writeFileSync(CANDIDATES_OUT, candidatesContent, 'utf8');
const candidatesSizeKB = (fs.statSync(CANDIDATES_OUT).size / 1024).toFixed(1);
console.log(`Built ${path.relative(repoRoot, CANDIDATES_OUT)} (${candidatesSizeKB} KB)`);
